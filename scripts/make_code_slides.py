import json
import math
import os
import re
import sys

ROOT = sys.argv[1]
FILES = [                                                         # (path in repo, label, listings language)
    ('scripts/verify_nanoaod_files.py', 'verify_nanoaod_files.py', 'Python'),
    ('scripts/deadbits.py', 'deadbits.py', 'Python'),
    ('scripts/menuscan.py', 'menuscan.py', 'Python'),
    ('scripts/menusummary.py', 'menusummary.py', 'Python'),
    ('scripts/pathmatrix.py', 'pathmatrix.py', 'Python'),
    ('scripts/bits.py', 'bits.py', 'Python'),
    ('scripts/bitfilters.py', 'bitfilters.py', 'Python'),
    ('scripts/wfn.py', 'wfn.py', 'Python'),
    ('scripts/measure_trigobj.py', 'measure_trigobj.py', 'Python'),
    ('scripts/make_fixed_nano.sh', 'make_fixed_nano.sh', 'bash'),
    ('scripts/relval_fix_check.sh', 'relval_fix_check.sh', 'bash'),
    ('scripts/compare_dqm.py', 'compare_dqm.py', 'Python'),
    ('slides/code/commands_as_run.sh', 'commands as run', 'bash'),
]
BEAMER = {'chars': 135, 'lines': 30}                              # visual line budget of one Beamer frame
HTML = {'chars': 150, 'lines': 34}                                # visual line budget of one HTML slide


def visual_lines(line, chars):
    # Total: time O(1), space O(1)
    return max(1, math.ceil(len(line) / chars))                   # - | wrapped lines one source line needs


def chunk(lines, budget):
    # Split lines into consecutive (first, last) ranges, 1-based, that fit the budget.
    # Total: time O(n), space O(n)
    ranges, start, used = [], 0, 0                                # list | ranges found so far
    for i, line in enumerate(lines):                              # O(n) | greedy fill
        need = visual_lines(line, budget['chars'])
        new_block = line.startswith('# ---') or line.startswith('# =====') or line.startswith('def ')
        if used and (used + need > budget['lines'] or (new_block and used + 8 > budget['lines'])):
            ranges.append((start + 1, i))                         # - | close the current frame
            start, used = i, 0
        used += need
    ranges.append((start + 1, len(lines)))
    return ranges


def group_of(lines, first):
    # Name of the '# ===== N. ...' group the line `first` belongs to (commands file only).
    # Total: time O(n), space O(1)
    name = ''
    for line in lines[:first]:                                    # O(n) | last group header above the range
        if line.startswith('# ====='):
            name = line[len('# ===== '):]
    return name


def frame_title(label, k, n, lines, first):
    # Total: time O(n), space O(1)
    title = f'{label} ({k}/{n})'
    if label == 'commands as run':
        title = f'commands as run: {group_of(lines, first)} ({k}/{n})'
    return title


def latex_escape(text):
    # Total: time O(len), space O(len)
    return text.replace('\\', r'\textbackslash{}').replace('_', r'\_').replace('&', r'\&').replace('#', r'\#')


def write_beamer(path):
    # Total: time O(total lines), space O(total lines)
    out = ['% Generated by make_code_slides.py: every script, and the commands as run, verbatim.',
           r'\partdivider{}{Backup: code}']
    for rel, label, lang in FILES:
        lines = open(os.path.join(ROOT, rel)).read().split('\n')
        ranges = chunk(lines, BEAMER)
        for k, (first, last) in enumerate(ranges, 1):             # O(frames) | one frame per range
            title = latex_escape(frame_title(label, k, len(ranges), lines, first))
            out.append(r'\begin{frame}{Backup code: ' + title + '}')
            out.append(r'  \vspace{0pt}\par')
            out.append(r'  {\tiny\color{lightgrey}\texttt{' + latex_escape(rel) + '}' + f', lines {first} to {last}' + r'\par}')
            out.append(f'  \\lstinputlisting[style=codebk,language={lang},firstline={first},lastline={last},firstnumber={first}]'
                       f'{{../../../{rel}}}')
            out.append(r'\end{frame}')
    open(path, 'w').write('\n'.join(out) + '\n')
    return sum(1 for line in out if line.startswith(r'\begin{frame}'))


SECTION = ('<section id="{id}" data-transition="fade" style="background:#F6F5F0;color:#16213A;'
           "font-family:'IBM Plex Sans', Arial, sans-serif;padding:56px 72px 72px 72px;display:flex;flex-direction:column;gap:12px\">")
H2 = '<h2 style="font-size:40px;font-weight:600;line-height:1.1">Backup code: {title}</h2>'
SUB = ("<p style=\"font-size:18px;line-height:1.2;color:#44506A;font-family:'JetBrains Mono', 'Courier New', monospace\">"
       '{rel}, lines {first} to {last}</p>')
PRE = ('<pre style="margin:0;flex:1;min-height:0;background:#16213A;color:#F6F5F0;border-radius:12px;padding:16px 22px;'
       "font-size:16.5px;line-height:1.3;font-family:'JetBrains Mono', 'Courier New', monospace;"
       'white-space:pre-wrap;overflow-wrap:anywhere;overflow:hidden">{code}</pre>')


def write_html(deck_root):
    # Total: time O(total lines), space O(total lines)
    slide_dir = os.path.join(deck_root, 'project/slides')
    deck_file = os.path.join(deck_root, 'project/deck.json')
    deck = json.load(open(deck_file))
    deck['order'] = [s for s in deck['order'] if not s.startswith('code-')]   # - | regenerate cleanly
    for name in os.listdir(slide_dir):
        if name.startswith('code-'):
            os.remove(os.path.join(slide_dir, name))
    new_ids = []
    for rel, label, lang in FILES:
        lines = open(os.path.join(ROOT, rel)).read().split('\n')
        ranges = chunk(lines, HTML)
        stem = re.sub(r'[^a-z0-9]+', '-', label.lower()).strip('-')
        for k, (first, last) in enumerate(ranges, 1):             # O(slides) | one slide per range
            slide_id = f'code-{stem}-{k}'
            code = html.escape('\n'.join(lines[first - 1:last]))
            body = '\n'.join([SECTION.format(id=slide_id),
                              H2.format(title=html.escape(frame_title(label, k, len(ranges), lines, first))),
                              SUB.format(rel=html.escape(rel), first=first, last=last),
                              PRE.format(code=code), '</section>'])
            open(os.path.join(slide_dir, slide_id + '.html'), 'w').write(body + '\n')
            new_ids.append(slide_id)
    deck['order'] += new_ids
    deck['sections']['code'] = {'description': 'Backup: every script and the commands as run, verbatim',
                                'start': new_ids[0]}
    open(deck_file, 'w').write(json.dumps(deck, separators=(',', ':')))
    return len(new_ids)


n_beamer = write_beamer(os.path.join(ROOT, 'slides/beamer/src/code_backup.tex'))
n_detailed = write_html(os.path.join(ROOT, 'slides/detailed-deck-src'))
n_issue = write_html(os.path.join(ROOT, 'slides/issue-deck-src'))
print('beamer code frames', n_beamer, '| detailed deck code slides', n_detailed, '| issue deck code slides', n_issue)
